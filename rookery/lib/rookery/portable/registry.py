_GENERATED_AGENT_HEADER = b"# Generated by Rookery surface renderer.\n"
_WORKER_HANDOFF_INSTRUCTIONS = """## Identity
- Primary objective: Produce one verified, bounded result for the assigned role mission.

## Capabilities
- Use authorized local tools and write only the report and artifact paths named in the assignment.

## Inputs and outputs
- Read the complete worker card and any exact source report before acting. Return the assigned report with the canonical handoff block completed; done means the stop condition is met or a concrete blocker is recorded.
- A depth-1 challenge coordinator registers every child with `--parent-attempt-id` set to its own exact active attempt ID. Depth-2 workers must not delegate.

## Boundaries
- Stay inside the assigned scope and allowed actions. Do not infer scoring or platform-mutation authority; ordinary solvers only propose candidates.

## Escalation
- Stop at the assigned stop condition. Record a concrete blocker and return trigger when progress requires new authority, scope, external state, or unavailable infrastructure.

## Report handoff
- Use the exact report path and stop condition from your assignment. Write the report early; before integration replace every placeholder with current facts.
- Directly after the report title keep `## Handoff` with exact one-line labels in this order: `Status:`, `Source handoff:`, `Source report SHA-256:`, `Observed result:`, `Route key:`, `Proof gap:`, `Discriminating test:`, `Next step or return trigger:`, `Evidence paths:`, `Command/artifact paths:`, `Blocker:`, `Cleanup/jobs:`.
- `Route key` must match `[a-z0-9][a-z0-9._:-]{0,127}` exactly: ASCII lower case, no spaces, and at most 128 characters.
- `Status` must be one of `supported_finding`, `technical_negative`, `incomplete_evidence`, `generic_refusal`, `capacity_failure`, `environment_failure`, `duplicate_trace`, `invalid_scope`, `candidate`, `no_progress`, or `other`. Use `incomplete_evidence` while work is active.
- `Source handoff` and `Source report SHA-256` are `none` only for an initial route, including initial event-wide work. As a successor, open and read the exact source report before acting, cite its handoff ID and exact registered 64hex report hash, name a materially different route, and supply a nonempty `Discriminating test`.
- `Evidence paths` and `Command/artifact paths` are JSON arrays of current-workspace-relative POSIX paths to private regular artifacts below only `analysis/`, `evidence/`, `work/`, `exploit/`, `captures/`, or `downloads/`. Never put `state/`, `platform/`, absolute paths, outside-workspace paths, symlinks, or prose in those arrays. Copy any needed state or platform evidence into an allowed private artifact root first. Follow the handoff block with `## Evidence` and `## Commands`."""


def _render_agent_toml(source: Path) -> bytes:
    """Append the shared handoff contract while preserving role-specific text."""

    try:
        document = tomllib.loads(source.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        raise RuntimeError(f"selected agent definition is invalid: {source}") from exc
    if set(document) != {
        "name",
        "description",
        "developer_instructions",
        "nickname_candidates",
    }:
        raise RuntimeError(f"selected agent definition has unsupported fields: {source}")
    if any(
        not isinstance(document.get(key), str)
        for key in ("name", "description", "developer_instructions")
    ):
        raise RuntimeError(f"selected agent definition has invalid text: {source}")
    nicknames = document.get("nickname_candidates")
    if not isinstance(nicknames, list) or any(
        not isinstance(nickname, str) for nickname in nicknames
    ):
        raise RuntimeError(f"selected agent definition has invalid nicknames: {source}")
    instructions = str(document["developer_instructions"]).rstrip()
    if "## Report handoff" in instructions:
        raise RuntimeError(f"selected agent definition duplicates shared handoff text: {source}")
    instructions = instructions + "\n\n" + _WORKER_HANDOFF_INSTRUCTIONS + "\n"
    rendered = (
        f"name = {json.dumps(document['name'])}\n"
        f"description = {json.dumps(document['description'])}\n"
        f"developer_instructions = {json.dumps(instructions)}\n"
        f"nickname_candidates = {json.dumps(nicknames)}\n"
    )
    return rendered.encode("utf-8")


def _directory_flags() -> int:
    return os.O_RDONLY | getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_NOFOLLOW", 0)


def _open_root(root: Path) -> tuple[Path, int]:
    """Open the supplied workspace itself, not a resolved/link target."""

    absolute = Path(os.path.abspath(os.fspath(root)))
    info = os.lstat(absolute)
    if stat.S_ISLNK(info.st_mode) or not stat.S_ISDIR(info.st_mode):
        raise RuntimeError(f"workspace root must be a non-link directory: {root}")
    try:
        descriptor = os.open(absolute, _directory_flags())
    except OSError as exc:
        raise RuntimeError(f"unable to safely open workspace root: {root}") from exc
    return absolute, descriptor


def _open_child_directory(parent: int, name: str, display: Path) -> int:
    """Create or open exactly one contained directory without following it."""

    try:
        info = os.stat(name, dir_fd=parent, follow_symlinks=False)
    except FileNotFoundError:
        try:
            os.mkdir(name, 0o700, dir_fd=parent)
        except FileExistsError:
            pass
    else:
        if stat.S_ISLNK(info.st_mode) or not stat.S_ISDIR(info.st_mode):
            raise RuntimeError(f"generated path is not a directory: {display}")
    try:
        child = os.open(name, _directory_flags(), dir_fd=parent)
    except OSError as exc:
        raise RuntimeError(f"unable to safely open generated directory: {display}") from exc
    try:
        info = os.fstat(child)
        if not stat.S_ISDIR(info.st_mode):
            raise RuntimeError(f"generated path is not a directory: {display}")
        return child
    except BaseException:
        os.close(child)
        raise


def _existing_regular_at(parent: int, name: str, display: Path) -> os.stat_result | None:
    try:
        info = os.stat(name, dir_fd=parent, follow_symlinks=False)
    except FileNotFoundError:
        return None
    if stat.S_ISLNK(info.st_mode) or not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        raise RuntimeError(f"generated target is not an unlinked regular file: {display}")
    return info


def _read_regular_at(parent: int, name: str, display: Path) -> bytes:
    _existing_regular_at(parent, name, display)
    flags = os.O_RDONLY | getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_NOFOLLOW", 0)
    try:
        descriptor = os.open(name, flags, dir_fd=parent)
    except OSError as exc:
        raise RuntimeError(f"unable to safely read generated file: {display}") from exc
    try:
        info = os.fstat(descriptor)
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
            raise RuntimeError(f"generated target changed while reading: {display}")
        chunks: list[bytes] = []
        while True:
            chunk = os.read(descriptor, 64 * 1024)
            if not chunk:
                return b"".join(chunks)
            chunks.append(chunk)
    finally:
        os.close(descriptor)


def _atomic_private_write_at(parent: int, name: str, data: bytes, display: Path) -> None:
    """Atomically replace one verified target inside an already-open directory."""

    _existing_regular_at(parent, name, display)
    temporary = ""
    descriptor: int | None = None
    try:
        for _ in range(32):
            temporary = f".{name}.{secrets.token_hex(16)}.tmp"
            try:
                descriptor = os.open(
                    temporary,
                    os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_NOFOLLOW", 0),
                    0o600,
                    dir_fd=parent,
                )
                break
            except FileExistsError:
                continue
        if descriptor is None:
            raise RuntimeError(f"unable to reserve generated temporary file: {display}")
        offset = 0
        while offset < len(data):
            offset += os.write(descriptor, data[offset:])
        os.fchmod(descriptor, 0o600)
        os.fsync(descriptor)
        os.close(descriptor)
        descriptor = None
        os.replace(temporary, name, src_dir_fd=parent, dst_dir_fd=parent)
        os.fsync(parent)
    finally:
        if descriptor is not None:
            os.close(descriptor)
        if temporary:
            try:
                os.unlink(temporary, dir_fd=parent)
            except FileNotFoundError:
                pass


def _clean_generated_agents(parent: int, display: Path) -> None:
    for name in os.listdir(parent):
        if not name.endswith(".toml"):
            continue
        path = display / name
        _existing_regular_at(parent, name, path)
        if _read_regular_at(parent, name, path).startswith(_GENERATED_AGENT_HEADER):
            os.unlink(name, dir_fd=parent)
    os.fsync(parent)


def rendered_codex_config(
    config: Path,
    *,
    max_concurrent_threads: int,
    strict_config_supported: bool,
) -> bytes:
    """Return the one canonical generated Codex config for a bound manifest."""

    if (
        isinstance(max_concurrent_threads, bool)
        or not isinstance(max_concurrent_threads, int)
        or max_concurrent_threads < 1
    ):
        raise RuntimeError("resolved Codex thread cap must be a positive integer")
    config_bytes = config.read_bytes()
    expected_policy = codex_shell_policy_toml().encode("utf-8")
    expected_shell = {
        "inherit": "core",
        "experimental_use_profile": False,
        "ignore_default_excludes": False,
        "filters": {
            line.split('"', 2)[1]: "include" for line in codex_shell_policy_toml().splitlines() if line.startswith('"')
        },
    }
    try:
        parsed_config = tomllib.loads(config_bytes.decode("utf-8"))
    except (UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        raise RuntimeError("selected Codex config is not valid UTF-8 TOML") from exc
    configured_shell = parsed_config.get("shell_environment_policy")
    configured_agents = parsed_config.get("agents")
    if not isinstance(configured_agents, dict):
        raise RuntimeError("selected Codex config is missing the agents table")
    if "max_threads" in configured_agents:
        raise RuntimeError("selected Codex config uses the legacy max_threads key")
    if "max_concurrent_threads_per_session" not in configured_agents:
        raise RuntimeError("selected Codex config is missing the agent thread cap")
    if configured_agents.get("max_depth") != 2:
        raise RuntimeError("selected Codex config must set max_depth to 2")
    text = config_bytes.decode("utf-8")
    lines = text.splitlines(keepends=True)
    in_agents = False
    replaced = 0
    for index, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            in_agents = stripped == "[agents]"
            continue
        if in_agents and re.match(r"^\s*max_concurrent_threads_per_session\s*=", line):
            if line.endswith("\r\n"):
                newline = "\r\n"
            elif line.endswith("\n"):
                newline = "\n"
            else:
                newline = ""
            lines[index] = f"max_concurrent_threads_per_session = {max_concurrent_threads}{newline}"
            replaced += 1
    if replaced != 1:
        raise RuntimeError("selected Codex config must define one agent thread cap")
    config_bytes = "".join(lines).encode("utf-8")
    if configured_shell is not None:
        if configured_shell != expected_shell:
            raise RuntimeError("selected Codex config has a noncanonical shell environment policy")
        if not strict_config_supported:
            raise RuntimeError("selected Codex config requires unsupported strict-config policy")
    elif strict_config_supported:
        if config_bytes and not config_bytes.endswith(b"\n"):
            config_bytes += b"\n"
        config_bytes += b"\n" + expected_policy
    return config_bytes


def _render_codex_files(
    root: Path,
    agents: list[dict[str, Any]],
    config: Path,
    *,
    max_concurrent_threads: int,
    strict_config_supported: bool,
) -> None:
    """Write generated Codex files below root using descriptor-contained paths."""

    root_path, root_fd = _open_root(root)
    codex_fd: int | None = None
    agents_fd: int | None = None
    try:
        codex_fd = _open_child_directory(root_fd, ".codex", root_path / ".codex")
        agents_fd = _open_child_directory(codex_fd, "agents", root_path / ".codex" / "agents")
        # Validate config before cleaning agents so a hostile config target
        # cannot cause a partial surface update before we reject it.
        _existing_regular_at(codex_fd, "config.toml", root_path / ".codex" / "config.toml")
        _clean_generated_agents(agents_fd, root_path / ".codex" / "agents")
        for entry in agents:
            source = root_path / str(entry["source"])
            if not source.exists():
                raise FileNotFoundError(source)
            _atomic_private_write_at(
                agents_fd,
                source.name,
                _GENERATED_AGENT_HEADER + _render_agent_toml(source),
                root_path / ".codex" / "agents" / source.name,
            )
        config_bytes = rendered_codex_config(
            config,
            max_concurrent_threads=max_concurrent_threads,
            strict_config_supported=strict_config_supported,
        )
        _atomic_private_write_at(
            codex_fd,
            "config.toml",
            config_bytes,
            root_path / ".codex" / "config.toml",
        )
    finally:
        if agents_fd is not None:
            os.close(agents_fd)
        if codex_fd is not None:
            os.close(codex_fd)
        os.close(root_fd)


def _load_list(path: Path) -> list[dict[str, Any]]:
    data = load_json(path, [])
    if not isinstance(data, list):
        raise ValueError(f"invalid registry: {path}")
    return data


def load_registry(root: Path, kind: str, manifest: dict[str, Any] | None = None) -> list[dict[str, Any]]:
    entries = _load_list(root / "registry" / f"{kind}.json")
    if manifest is None:
        return entries
    adapter_id = str(manifest.get("adapter", {}).get("id", "manual"))
    desc = adapter_descriptor(root, adapter_id)
    if desc:
        rel = desc.get(kind)
        if rel:
            entries.extend(_load_list(root / "adapters" / adapter_id / str(rel)))
    for extension_id in manifest.get("surface", {}).get("extensions", []) or []:
        ext = extension_descriptor(root, str(extension_id))
        rel = ext.get(kind)
        if rel:
            entries.extend(_load_list(root / "extensions" / str(extension_id) / str(rel)))
    ids: set[str] = set()
    out: list[dict[str, Any]] = []
    for entry in entries:
        ident = str(entry.get("id", ""))
        if ident in ids:
            raise ValueError(f"duplicate registry id across active bundles: {ident}")
        ids.add(ident)
        out.append(entry)
    return out


def selected_capabilities(manifest: dict[str, Any]) -> set[str]:
    capabilities = {"core", "local_shell"}
    capabilities.update(manifest.get("capabilities", {}).get("required", []))
    capabilities.update(manifest.get("surface", {}).get("bundles", []))
    capabilities.update(manifest.get("surface", {}).get("categories", []))
    capabilities.update(manifest.get("surface", {}).get("available_capabilities", []))
    capabilities.update(f"extension:{x}" for x in manifest.get("surface", {}).get("extensions", []) or [])
    adapter = manifest.get("adapter", {}).get("id")
    if adapter and adapter != "unknown":
        capabilities.add(f"adapter:{adapter}")
    return capabilities


def select_entries(entries: list[dict[str, Any]], manifest: dict[str, Any]) -> list[dict[str, Any]]:
    caps = selected_capabilities(manifest)
    out = []
    for entry in entries:
        requires = set(entry.get("requires_any", []))
        requires_all = set(entry.get("requires_all", []))
        if requires_all and not requires_all.issubset(caps):
            continue
        if requires and not (requires & caps):
            continue
        out.append(entry)
    return sorted(out, key=lambda x: x.get("id", ""))


def validate_admission(entries: list[dict[str, Any]], *, kind: str = "entry") -> list[str]:
    errors = []
    contracts: dict[str, str] = {}
    for entry in entries:
        ident = str(entry.get("id", ""))
        admission = entry.get("admission", {})
        if not ident:
            errors.append(f"{kind} registry entry missing id")
            continue
        if not admission.get("capability_gap"):
            errors.append(f"{ident}: missing admission.capability_gap")
        if not admission.get("evidence"):
            errors.append(f"{ident}: missing admission.evidence")
        if "legacy-optional" in set(entry.get("requires_any", [])) | set(entry.get("requires_all", [])):
            errors.append(
                f"{ident}: legacy-optional has no activation route; keep it as a raw compatibility command or remove it"
            )
        contract = str(admission.get("distinct_contract", ""))
        if not contract:
            errors.append(f"{ident}: missing admission.distinct_contract")
        elif contract in contracts and contracts[contract] != ident:
            errors.append(f"{ident}: duplicate contract with {contracts[contract]}: {contract}")
        else:
            contracts[contract] = ident
    return errors


def _codex_config(root: Path, manifest: dict[str, Any]) -> Path:
    adapter_id = str(manifest.get("adapter", {}).get("id", "manual"))
    desc = adapter_descriptor(root, adapter_id)
    if desc and desc.get("codex_config"):
        candidate = root / "adapters" / adapter_id / str(desc["codex_config"])
        if candidate.exists():
            return candidate
    return root / "configs" / "codex-base.toml"


def render_surface(
    root: Path,
    manifest: dict[str, Any],
    *,
    strict_config_supported: bool = True,
) -> dict[str, Any]:
    all_agents = load_registry(root, "agents", manifest)
    all_tools = load_registry(root, "tools", manifest)
    agents = select_entries(all_agents, manifest)
    tools = select_entries(all_tools, manifest)
    admission_errors = validate_admission(all_agents, kind="agent") + validate_admission(all_tools, kind="tool")
    if admission_errors:
        raise RuntimeError("surface admission validation failed: " + "; ".join(admission_errors[:10]))
    # Production launch passes a resolved manifest. Small read-only surface
    # fixtures may omit concurrency; retain the safe template cap for them.
    thread_cap = manifest.get("concurrency", {}).get("max_subagent_threads")
    if thread_cap is None:
        thread_cap = 96
    _render_codex_files(
        root,
        agents,
        _codex_config(root, manifest),
        max_concurrent_threads=thread_cap,
        strict_config_supported=strict_config_supported,
    )
    inventory = {
        "project": "rookery",
        "profile": manifest.get("profile"),
        "adapter": manifest.get("adapter", {}).get("id"),
        "extensions": list(manifest.get("surface", {}).get("extensions", []) or []),
        "capabilities": sorted(selected_capabilities(manifest)),
        "agents": [
            {
                "id": x["id"],
                "source": x["source"],
                "contract": x.get("admission", {}).get("distinct_contract"),
            }
            for x in agents
        ],
        "tools": [{"id": x["id"], "path": x.get("path"), "purpose": x.get("purpose")} for x in tools],
    }
    atomic_write_json(root / "state" / "active_surface.json", inventory)
    lines = [
        "# Active Rookery Surface",
        "",
        f"Profile: `{inventory['profile']}`",
        f"Adapter: `{inventory['adapter']}`",
    ]
    if inventory["extensions"]:
        lines.append(f"Extensions: `{', '.join(inventory['extensions'])}`")
    lines += ["", "## Agents"] + [f"- `{x['id']}` — {x['contract']}" for x in inventory["agents"]]
    lines += ["", "## Tools"] + [f"- `{x['id']}` — {x['purpose']}" for x in inventory["tools"]]
    atomic_write_text(root / "ACTIVE_SURFACE.md", "\n".join(lines) + "\n")
    return inventory
